-- Threat-observability findings (deduplicated, enriched, scored). Mirrors the Finding entity.
create table security_finding (
    id                 bigint generated by default as identity primary key,
    fingerprint        varchar(200) not null,
    rule_id            varchar(32)  not null,
    title              varchar(200) not null,
    severity           varchar(16)  not null,
    risk_score         integer      not null,
    status             varchar(16)  not null,
    owasp_category     varchar(120),
    attack_tactic      varchar(60),
    attack_technique   varchar(120),
    actor              varchar(64),
    source_ip          varchar(64),
    affected_account_id bigint,
    occurrence_count   integer      not null,
    first_seen         timestamp    not null,
    last_seen          timestamp    not null,
    evidence           varchar(1000),
    intel              varchar(255)
);
-- Deduplication lookup: active finding with this fingerprint seen recently.
create index idx_finding_fingerprint on security_finding (fingerprint, status, last_seen desc);
-- Analyst view: highest risk first.
create index idx_finding_risk on security_finding (risk_score desc, last_seen desc);
